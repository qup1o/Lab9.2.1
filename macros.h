// macros.h
// заголовний файл – макроси для обчислень та виведення результатів
#pragma once

#include <iostream>

#define SQR(x)    ((x) * (x))                  // квадрат числа
#define CUBE(x)   ((x) * (x) * (x))            // куб числа
#define ABS(x)    (((x) < 0) ? -(x) : (x))     // модуль числа
#define MAX(a, b) (((a) > (b)) ? (a) : (b))    // максимум з двох чисел
#define MIN(a, b) (((a) < (b)) ? (a) : (b))    // мінімум з двох чисел

// вираз для гілки z > 10:  max(x^3, (x + y)^2)
#define W_HIGH(x, y) MAX(CUBE(x), SQR((x) + (y)))

// вираз для гілки z <= 10:  min(|x - z|, |x + z|)
#define W_LOW(x, z)  MIN(ABS((x) - (z)), ABS((x) + (z)))

// виведення імені виразу та його значення; '#' перетворює параметр на рядок
#define PRINTR(w) std::cout << #w << " = " << (w) << std::endl
